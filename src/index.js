const active = new Map();

export default {
  async fetch(request, env) {
    if (request.method !== "POST") return new Response("TNPSC Quiz Bot is running");
    try {
      const update = await request.json();
      if (update.message) await onMessage(update.message,env);
      if (update.callback_query) await onCallback(update.callback_query,env);
      if (update.poll_answer) await onPollAnswer(update.poll_answer,env);
    } catch (err) {
      console.error("BOT_ERROR:",err?.stack || err?.message || String(err));
    }
    return new Response("OK");
  }
};

async function api(env,method,body) {
  const r = await fetch(`https://api.telegram.org/bot${env.TELEGRAM_BOT_TOKEN}/${method}`,{
    method:"POST",
    headers:{"content-type":"application/json"},
    body:JSON.stringify(body)
  });
  const data = await r.json();
  if (!data.ok) console.error("TELEGRAM_ERROR:",JSON.stringify(data));
  return data;
}

async function say(env,chat,text,extra={}) {
  return api(env,"sendMessage",{chat_id:chat,text,...extra});
}

async function onMessage(m,env) {
  const uid = String(m.from.id);
  const chat = String(m.chat.id);
  const t = (m.text || "").trim();

  if (t === "/start" || t === "/menu" || t === "🏠 முதன்மை Menu") {
    return say(env,chat,`வணக்கம்! TNPSC Group 4 Quiz Bot.\n\nமொத்த வினாக்கள்: ${QUESTIONS.length}\nதேர்வைத் தேர்வு செய்யுங்கள்.`,{reply_markup:MENU});
  }
  if (t === "📝 தேர்வு (25)") return begin(env,uid,chat,25);
  if (t === "🔥 கடினத் தேர்வு (50)") return begin(env,uid,chat,50);
  if (t === "🏆 முழுத் தேர்வு (100)") return begin(env,uid,chat,100);
  if (t === "📚 பாடவாரித் தேர்வு") return say(env,chat,"பாடத்தைத் தேர்வு செய்யுங்கள்.",{reply_markup:SUBJECTS});
  if (t === "📊 மதிப்பெண்கள்") {
    const s = active.get(uid);
    return say(env,chat,s ? `📊 மதிப்பெண்: ${s.score}/${s.index}` : "இப்போது செயலில் உள்ள தேர்வு இல்லை.",{reply_markup:MENU});
  }
  if (t === "📖 படிப்பு முறை") {
    return say(env,chat,"ஒவ்வொரு வினாவிற்கும் ஒரு பதிலைத் தேர்வு செய்யுங்கள். பதிலுக்குப் பிறகு விளக்கமும் அடுத்த வினாவும் வரும்.",{reply_markup:MENU});
  }
  return say(env,chat,"Menu-வில் உள்ள தேர்வைத் தேர்வு செய்யுங்கள்.",{reply_markup:MENU});
}

async function onCallback(q,env) {
  await api(env,"answerCallbackQuery",{callback_query_id:q.id});
  const data = q.data || "";
  if (!data.startsWith("S:")) return;
  const subject = data.slice(2);
  const list = QUESTIONS.filter(x => x.s === subject);
  if (!list.length) return say(env,String(q.message.chat.id),"இந்தப் பாடத்தில் வினாக்கள் இல்லை.");
  return startWithList(env,String(q.from.id),String(q.message.chat.id),list);
}

async function begin(env,uid,chat,count) {
  const shuffled = [...QUESTIONS].sort(() => Math.random()-0.5);
  return startWithList(env,uid,chat,shuffled.slice(0,Math.min(count,shuffled.length)));
}

async function startWithList(env,uid,chat,questions) {
  active.set(uid,{chat,questions,index:0,score:0,waiting:null,answered:new Set()});
  await say(env,chat,`📝 தேர்வு தொடங்குகிறது!\nமொத்த வினாக்கள்: ${questions.length}`);
  return nextQuestion(env,uid);
}

async function nextQuestion(env,uid) {
  const s = active.get(uid);
  if (!s) return;
  if (s.index >= s.questions.length) {
    const score = s.score, total = s.questions.length;
    active.delete(uid);
    return say(env,s.chat,`🏁 தேர்வு முடிந்தது!\n\nமொத்த வினாக்கள்: ${total}\nசரியான பதில்கள்: ${score}\nதவறான பதில்கள்: ${total-score}`,{reply_markup:MENU});
  }

  const q = s.questions[s.index];
  const result = await api(env,"sendPoll",{
    chat_id:s.chat,
    question:`வினா ${s.index+1}/${s.questions.length}\n${q.q}`,
    options:q.o,
    type:"quiz",
    correct_option_id:q.a,
    is_anonymous:false,
    explanation:q.e
  });

  if (!result.ok) {
    return say(env,s.chat,"வினாவை அனுப்ப முடியவில்லை. Telegram webhook அமைப்பைச் சரிபார்க்கவும்.",{reply_markup:MENU});
  }

  s.waiting={pollId:result.result.poll.id,messageId:result.result.message_id,question:q};
}

async function onPollAnswer(a,env) {
  if (!a.user || !a.option_ids || !a.option_ids.length) return;
  const uid=String(a.user.id);
  const s=active.get(uid);
  if (!s || !s.waiting || s.waiting.pollId!==a.poll_id) return;
  if (s.answered.has(a.poll_id)) return;
  s.answered.add(a.poll_id);

  const q=s.waiting.question;
  const correct=a.option_ids[0]===q.a;
  await api(env,"stopPoll",{chat_id:s.chat,message_id:s.waiting.messageId});
  if (correct) s.score++;
  s.index++;
  s.waiting=null;

  await say(env,s.chat,
    `${correct ? "✅ சரியான பதில்!" : `❌ தவறான பதில்!\nசரியான பதில்: ${q.o[q.a]}`}\n\n📘 விளக்கம்: ${q.e}\n📊 மதிப்பெண்: ${s.score}/${s.index}`
  );
  return nextQuestion(env,uid);
}
